    // Хелперы
    static func single(_ n: Int, _ q: String, _ opts: [String], _ ans: String, _ expl: String, _ topic: String) -> ExamTask {
        ExamTask(number: n, type: .singleChoice, question: q, options: opts, matchingItems: nil,
                 correctAnswer: ans, explanation: expl, topic: topic)
    }
    static func multi(_ n: Int, _ q: String, _ opts: [String], _ ans: String, _ expl: String, _ topic: String) -> ExamTask {
        ExamTask(number: n, type: .multipleChoice, question: q, options: opts, matchingItems: nil,
                 correctAnswer: ans, explanation: expl, topic: topic)
    }
    static func matching(_ n: Int, _ q: String, _ opts: [String], _ items: [String], _ ans: String, _ expl: String, _ topic: String) -> ExamTask {
        ExamTask(number: n, type: .matching, question: q, options: opts, matchingItems: items,
                 correctAnswer: ans, explanation: expl, topic: topic)
    }
    static func short(_ n: Int, _ q: String, _ ans: String, _ expl: String, _ topic: String) -> ExamTask {
        ExamTask(number: n, type: .shortAnswer, question: q, options: nil, matchingItems: nil,
                 correctAnswer: ans, explanation: expl, topic: topic)
    }
    static func eq(_ n: Int, _ q: String, _ ans: String, _ expl: String, _ topic: String) -> ExamTask {
        ExamTask(number: n, type: .equationInput, question: q, options: nil, matchingItems: nil,
                 correctAnswer: ans, explanation: expl, topic: topic)
    }

    static func generateVariant(count: Int = 10) -> ExamVariant {
        // Стараемся брать разные типы
        var byType: [ExamTaskType: [ExamTask]] = [:]
        for t in allTasks {
            byType[t.type, default: []].append(t)
        }
        var picked: [ExamTask] = []
        let order: [ExamTaskType] = [.singleChoice, .multipleChoice, .matching, .shortAnswer, .equationInput]
        var i = 0
        while picked.count < count {
            let type = order[i % order.count]
            if let list = byType[type], !list.isEmpty {
                let candidate = list[Int.random(in: 0..<list.count)]
                if !picked.contains(where: { $0.id == candidate.id }) {
                    picked.append(candidate)
                } else {
                    // перебор
                    var attempts = 0
                    while attempts < 20 {
                        let c = list[Int.random(in: 0..<list.count)]
                        if !picked.contains(where: { $0.id == c.id }) {
                            picked.append(c)
                            break
                        }
                        attempts += 1
                    }
                }
            }
            i += 1
            if i > 200 { break }
        }
        return ExamVariant(id: UUID(), title: "Тренировочный вариант", tasks: picked.shuffled())
    }
